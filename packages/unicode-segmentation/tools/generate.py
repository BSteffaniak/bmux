"""Regenerate src/properties.rs offline from Unicode 17.0.0 (Python 3)."""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data/17.0.0"
OUTPUT = ROOT / "src/properties.rs"
GCB = "Other CR LF Control Extend ZWJ Regional_Indicator Prepend SpacingMark L V T LV LVT".split()
INCB = ["None", "Consonant", "Extend", "Linker"]


def verify_inputs():
    manifest = {}
    for line in (DATA / "SHA256SUMS").read_text(encoding="ascii").splitlines():
        digest, name = line.split()
        manifest[name] = digest
    if set(manifest) != {"GraphemeBreakProperty.txt", "emoji-data.txt", "DerivedCoreProperties.txt", "LICENSE.txt"}:
        raise ValueError("incomplete Unicode input manifest")
    for name, digest in manifest.items():
        if hashlib.sha256((DATA / name).read_bytes()).hexdigest() != digest:
            raise ValueError(f"checksum mismatch: {name}")


def records(name):
    for line in (DATA / name).read_text(encoding="utf-8").splitlines():
        content = line.partition("#")[0].strip()
        if content:
            span, *fields = (part.strip() for part in content.split(";"))
            ends = span.split("..")
            yield range(int(ends[0], 16), int(ends[-1], 16) + 1), fields


def packed_properties():
    # Unlisted code points have GCB=Other, Extended_Pictographic=No, InCB=None.
    props = bytearray(0x110000)
    for points, (gcb,) in records("GraphemeBreakProperty.txt"):
        props[points.start:points.stop] = bytes([GCB.index(gcb)]) * len(points)
    for points, fields in records("emoji-data.txt"):
        if fields == ["Extended_Pictographic"]:
            for cp in points:
                props[cp] |= 0x10
    for points, fields in records("DerivedCoreProperties.txt"):
        if fields[0] == "InCB":
            value = INCB.index(fields[1]) << 5
            for cp in points:
                props[cp] |= value
    return props


def rust_array(name, data):
    lines = ["#[rustfmt::skip]", f"static {name}: [u8; {len(data)}] = ["]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(map(str, data[i:i + 24])) + ",")
    return "\n".join(lines + ["];\n"])


def generate():
    props = packed_properties()
    # Assign each distinct page an ID at its first occurrence in code point order.
    pages = {}
    index = bytearray()
    for i in range(0, len(props), 256):
        page = bytes(props[i:i + 256])
        index.append(pages.setdefault(page, len(pages)))
    return """// Generated by tools/generate.py from Unicode 17.0.0. Do not edit.
// Unicode data license: data/17.0.0/LICENSE.txt.

/// Bits 0..=3: GCB; bit 4: Extended_Pictographic; bits 5..=6: InCB.
#[inline]
pub(crate) fn lookup(ch: char) -> u8 {
    let cp = ch as usize;
    let page = usize::from(PAGE_INDEX[cp >> 8]);
    PAGE_DATA[(page << 8) | (cp & 0xff)]
}

""" + rust_array("PAGE_INDEX", index) + "\n" + rust_array("PAGE_DATA", b"".join(pages)) + """
#[cfg(test)]
#[path = "../tools/verify_properties.rs"]
mod verify_properties;
"""


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare generated bytes without writing")
    args = parser.parse_args()
    verify_inputs()
    generated = generate().encode("ascii")
    if args.check:
        if OUTPUT.read_bytes() != generated:
            raise SystemExit("src/properties.rs is stale; run tools/generate.py")
    else:
        OUTPUT.write_bytes(generated)
